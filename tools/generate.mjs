import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

if (process.argv.length !== 4) {
    throw new Error('Usage: generate.mjs SOURCES OUTPUT');
}
const [sources, output] = process.argv.slice(2).map(path => resolve(path));
const hostCompiler = process.env.HOST_CC ?? 'cc';
const stage = join(output, 'stage');
const tools = join(stage, 'tools');
mkdirSync(tools, { recursive: true });

function run(command, args, cwd) {
    return execFileSync(command, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
}

function pkgConfig(...args) {
    return run('pkg-config', args).trim().split(/\s+/).filter(Boolean);
}

function buildTool(name, sourceFiles, extraArgs = []) {
    const executable = join(tools, name);
    run(hostCompiler, ['-O1', '-w', '-o', executable, ...sourceFiles, ...extraArgs]);
    return executable;
}

function publish(path, contents) {
    mkdirSync(dirname(path), { recursive: true });
    let existing = null;
    try {
        existing = readFileSync(path, 'utf8');
    } catch {
    }
    if (existing !== contents) {
        writeFileSync(path, contents);
    }
}

function publishFromStage(path, produce) {
    const staged = join(stage, 'out', basename(path));
    mkdirSync(dirname(staged), { recursive: true });
    produce(staged);
    publish(path, readFileSync(staged, 'utf8'));
}

function runPerlScript(library, script, input, generated) {
    const directory = join(stage, library);
    for (const file of [script, input]) {
        mkdirSync(dirname(join(directory, file)), { recursive: true });
        copyFileSync(join(sources, library, file), join(directory, file));
    }
    mkdirSync(dirname(join(directory, generated)), { recursive: true });
    run('perl', [script], directory);
    publish(join(output, library, basename(generated)), readFileSync(join(directory, generated), 'utf8'));
}

runPerlScript('libparserutils', 'build/make-aliases.pl', 'build/Aliases', 'src/charset/aliases.inc');
runPerlScript('libhubbub', 'build/make-entities.pl', 'build/Entities', 'src/tokeniser/entities.inc');

const elementTypes = run('gperf', ['element-type.gperf'], join(sources, 'libhubbub/src/treebuilder'));
publish(join(output, 'libhubbub/treebuilder/autogenerated-element-type.c'),
    elementTypes.replace(/^(const struct element_type_map)/m, 'static $1'));

for (const header of ['parser.h', 'errors.h']) {
    publish(join(output, 'libdom/include/dom/bindings/hubbub', header),
        readFileSync(join(sources, 'libdom/bindings/hubbub', header), 'utf8'));
}

const propertiesDirectory = join(sources, 'libcss/src/parse/properties');
const propertyParser = buildTool('css_property_parser_gen', [join(propertiesDirectory, 'css_property_parser_gen.c')]);
const properties = readFileSync(join(propertiesDirectory, 'properties.gen'), 'utf8').split('\n')
    .filter(line => /^[^#][^:]+:/.test(line));
for (const property of properties) {
    const name = property.slice(0, property.indexOf(':'));
    publishFromStage(join(output, 'libcss', `autogenerated_${name}.c`), staged => run(propertyParser, ['-o', staged, property]));
}

const netsurf = join(sources, 'netsurf');
const netsurfOutput = join(output, 'netsurf');
const revision = run('git', ['-C', netsurf, 'rev-parse', 'HEAD']).trim();
const commitDate = run('git', ['-C', netsurf, 'log', '-1', '--format=%cd', '--date=format:%d/%m/%Y %H:%M']).trim();
publish(join(netsurfOutput, 'testament.h'), [
    '#ifndef NETSURF_REVISION_TESTAMENT',
    `#define NETSURF_REVISION_TESTAMENT "${revision}"`,
    '#define USERNAME "netsurf-ce"',
    '#define GECOS "netsurf-ce"',
    '#define WT_ROOT "netsurf-ce"',
    '#define WT_HOSTNAME "netsurf-ce"',
    `#define WT_COMPILEDATE "${commitDate}"`,
    '#define WT_BRANCHPATH "master"',
    '#define WT_BRANCHISMASTER 1',
    `#define WT_REVID "${revision}"`,
    '#define WT_MODIFIED 0',
    '#define WT_MODIFICATIONS { { "", "" } }',
    '#define WT_SBOM { NULL }',
    '#endif',
    '',
].join('\n'));

const splitMessages = buildTool('split-messages', [join(netsurf, 'tools/split-messages.c')], ['-I', netsurf, ...pkgConfig('--cflags', '--libs', 'zlib')]);
publishFromStage(join(netsurfOutput, 'Messages'), staged =>
    run(splitMessages, ['-l', 'en', '-p', 'fb', '-f', 'messages', '-o', staged, 'resources/FatMessages'], netsurf));

const framebufferResources = join(netsurf, 'frontends/framebuffer/res');
const bearssl = join(sources, 'bearssl');
const bearsslSources = readdirSync(join(bearssl, 'src'), { recursive: true }).filter(name => name.endsWith('.c')).map(name => join(bearssl, 'src', name));
const bearsslTools = readdirSync(join(bearssl, 'tools')).filter(name => name.endsWith('.c')).map(name => join(bearssl, 'tools', name));
const brssl = buildTool('brssl', [...bearsslTools, ...bearsslSources], ['-I', join(bearssl, 'inc'), '-I', join(bearssl, 'src')]);
publish(join(output, 'platform/trust-anchors.c'), [
    '#include <bearssl.h>',
    '',
    '#include "platform/trust_anchors.h"',
    run(brssl, ['ta', '-q', 'resources/ca-bundle'], netsurf).trimEnd(),
    '',
    'const br_x509_trust_anchor *ce_trust_anchors(size_t *count) {',
    '    *count = TAs_NUM;',
    '    return TAs;',
    '}',
    '',
].join('\n'));

const convertImage = buildTool('convert_image', [join(netsurf, 'tools/convert_image.c')], pkgConfig('--cflags', '--libs', 'libpng'));
const images = readFileSync(join(netsurf, 'frontends/framebuffer/Makefile'), 'utf8').split('\n')
    .map(line => line.match(/^FB_IMAGE_(\w+)\s*:=\s*(\S+)/)).filter(Boolean);
for (const [, name, file] of images) {
    publishFromStage(join(netsurfOutput, `image-${name}.c`), staged => run(convertImage, [file, staged, name], framebufferResources));
}
